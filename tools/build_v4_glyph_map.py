#!/usr/bin/env python3
"""Build the per-word QPC V4 (604 page fonts p1..p604.ttf) glyph table for quran_unified.db.

The DB's qpc_ligature column holds codes of the 47 QCF4_Hafs faces. Those codes are consecutive "slots"
per page; slots never stored as a word (waqf marks drawn by a following slot, sajdah overline/number) are gaps.
The 604 v4 page fonts use the same slot order starting at U+FC41 on every page, so a word's v4 string is the run
of v4 codes covering its slots up to the next stored word of the page.

Input : public/db/quran_unified.db, reference v4 word list (tools/data/qpc_v4_words.tsv.gz: verse_id, pos,
        type, page, line, code, text — Quran.com API v4 code_v4, same data the Quran Trainer renderer uses).
Output: public/db/qpc_v4_glyphs.tsv  (word_id \\t v4 string as hex code points separated by '+').
Checks every word against the reference where the word split agrees; fails on any mismatch.
"""
import gzip, sqlite3, sys, os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db = sqlite3.connect(os.path.join(ROOT, 'public/db/quran_unified.db'))
ref_path = os.path.join(ROOT, 'tools/data/qpc_v4_words.tsv.gz')
out_path = os.path.join(ROOT, 'app/src/main/assets/json/qpc-v4-glyphs.tsv')

vid = {}
for s, a in db.execute('select surah_id, ayah_number from ayahs order by surah_id, ayah_number'):
    vid[(s, a)] = len(vid) + 1
ref = {}; ref_page = collections.defaultdict(list)
for line in gzip.open(ref_path, 'rt', encoding='utf8'):
    v, pos, t, pg, ln, code, txt = line.rstrip('\n').split('\t')
    ref[(int(v), int(pos))] = code
    ref_page[int(pg)].extend(ord(c) for c in code)
words = db.execute('select word_id, surah_id, ayah_number, word_position, qpc_ligature from words '
                   'order by word_id').fetchall()
ayah_words = collections.defaultdict(list)
for w in words: ayah_words[(w[1], w[2])].append(w)
ref_ayah = collections.defaultdict(list)
for (v, pos) in sorted(ref): ref_ayah[v].append(ref[(v, pos)])
result = {}; errors = []; checked = 0; realigned = []
for key, ws in ayah_words.items():
    v = vid[key]; rs = ref_ayah[v]
    if len(ws) == len(rs):
        for w, r in zip(ws, rs): result[w[0]] = r.replace(' ', ''); checked += 1
        continue
    # Word split differs (e.g. «بَعۡدَ مَا» is one v4 word, two DB words): distribute the ayah's v4 glyphs
    # over the DB words by their 47-face slot runs (slots = consecutive codes, gaps = unstored marks).
    glyphs = ''.join(rs).replace(' ', ''); slots = [ord(w[4][0]) for w in ws]
    total = slots[-1] - slots[0] + len(ws[-1][4])
    if total != len(glyphs) or slots != sorted(slots):
        errors.append(f'{key}: {total} slots vs {len(glyphs)} v4 glyphs'); continue
    for i, w in enumerate(ws):
        a = slots[i] - slots[0]; b = (slots[i + 1] - slots[0]) if i + 1 < len(ws) else len(glyphs)
        result[w[0]] = glyphs[a:b]
    realigned.append(key)
print('realigned ayahs', realigned)
missing = [w[0] for w in words if w[0] not in result]
print(f'words {len(words)} mapped {len(result)} checked-vs-ref {checked} errors {len(errors)} missing {len(missing)}')
for e in errors[:20]: print(' ', e)
print('missing', [w for w in words if w[0] not in result][:20])
if errors or missing: sys.exit(1)
with open(out_path, 'w', encoding='utf8') as f:
    f.write('# word_id\tQPC V4 glyph code points (hex, +) for fonts/qcf4/pN.ttf — generated by tools/build_v4_glyph_map.py\n')
    for wid in sorted(result):
        f.write(f"{wid}\t{'+'.join('%x' % ord(c) for c in result[wid])}\n")
print('wrote', out_path)
