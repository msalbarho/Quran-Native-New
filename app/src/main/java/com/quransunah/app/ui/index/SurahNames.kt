    init {
        require(byLocale.keys == LanguageRegistry.tags) {
            "Surah name locales must match LanguageRegistry"
        }
        require(byLocale.values.all { it.size == COUNT }) {
            "Each locale must have $COUNT surah name slots"
        }
    }

    /** Verified localized name, or null when the Arabic fallback should be shown. */
    fun localized(languageTag: String?, surahNumber: Int): String? {
        if (surahNumber !in 1..COUNT) return null
        val tag = languageTag?.lowercase() ?: return null
        return byLocale[tag]?.getOrNull(surahNumber - 1)?.takeIf { it.isNotBlank() }
    }

    /** Localized name when present; otherwise the existing Arabic surah name. */
    fun displayName(languageTag: String?, surahNumber: Int, arabicName: String): String =
        localized(languageTag, surahNumber) ?: arabicName
}
